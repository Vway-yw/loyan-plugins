"""人生格言 — 随机人生格言（本地库）

命令：
  /格言     — 随机人生格言
"""

import random

from graci import on_command, plugin_handler, PluginContext, get_logger

logger = get_logger("人生格言")

# ── 常量定义 ──
QUOTES = [
    ("人生如逆旅，我亦是行人。", "苏轼"),
    ("路漫漫其修远兮，吾将上下而求索。", "屈原"),
    ("不积跬步，无以至千里；不积小流，无以成江海。", "荀子"),
    ("天行健，君子以自强不息。", "《周易》"),
    ("宝剑锋从磨砺出，梅花香自苦寒来。", "《警世贤文》"),
    ("千里之行，始于足下。", "《道德经》"),
    ("书山有路勤为径，学海无涯苦作舟。", "韩愈"),
    ("纸上得来终觉浅，绝知此事要躬行。", "陆游"),
    ("长风破浪会有时，直挂云帆济沧海。", "李白"),
    ("会当凌绝顶，一览众山小。", "杜甫"),
    ("生当作人杰，死亦为鬼雄。", "李清照"),
    ("有志者事竟成，破釜沉舟，百二秦关终属楚。", "蒲松龄"),
    ("冰冻三尺，非一日之寒。", "《论衡》"),
    ("百尺竿头，更进一步。", "《景德传灯录》"),
    ("知人者智，自知者明。", "《道德经》"),
    ("三人行，必有我师焉。", "《论语》"),
    ("己所不欲，勿施于人。", "《论语》"),
    ("勿以善小而不为，勿以恶小而为之。", "刘备"),
    ("海纳百川，有容乃大。", "林则徐"),
    ("天将降大任于斯人也，必先苦其心志。", "《孟子》"),
]


@on_command("/格言", "/人生格言", "/座右铭")
@plugin_handler
async def handle_quote(ctx: PluginContext):
    """随机格言"""
    quote, author = random.choice(QUOTES)
    await ctx.reply(f"📜 人生格言\n━━━━━━━━━━━━\n💬 {quote}\n—— {author}\n\n💡 /格言 换一句")
